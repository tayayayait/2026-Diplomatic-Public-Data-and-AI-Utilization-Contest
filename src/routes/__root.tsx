function RootShell({ children }: { children: React.ReactNode }) {
  return (
    <html lang="ko">
      <head>
        <HeadContent />
      </head>
      <body>
        <a href="#main-content" className="skip-link">
          본문으로 건너뛰기
        </a>
        {children}
        <Scripts />
        <script
          dangerouslySetInnerHTML={{
            __html: `
              if ('serviceWorker' in navigator) {
                window.addEventListener('load', () => {
                  navigator.serviceWorker.register('/sw.js').catch(err => {
                    console.error('ServiceWorker registration failed: ', err);
                  });
                });
              }
            `,
          }}
        />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
      </AuthProvider>
      <Toaster position="bottom-center" toastOptions={{
        classNames: {
          toast: 'bg-card border-border shadow-lg rounded-2xl p-4 flex gap-3',
          title: 'text-[14px] font-bold',
          description: 'text-[13px] text-muted-foreground',
          actionButton: 'bg-primary text-white rounded-lg px-3 py-1',
          cancelButton: 'bg-surface-alt text-muted-foreground rounded-lg px-3 py-1',
        }
      }} />
    </QueryClientProvider>
  );
}
